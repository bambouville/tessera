#!/usr/bin/env python3
"""Writes src/SearchFoldTable.h: the case and diacritic fold the host search
prefilter applies to text.

A character folds to its canonical decomposition, case-folded and decomposed
again, without any character the app's case- and diacritic-insensitive match
may ignore or the app's display text strips: marks, control and format
characters (joiners, tags, bidi controls), modifier letters and symbols
outside ASCII (skin tones, kana sound marks) and Hangul fillers. Space, line
and paragraph separators fold to a space. A code point this Unicode version
leaves unassigned may be one the app's newer Unicode folds or ignores: it is
listed apart, and SearchFold.h makes text holding one a candidate. Search matches with
that fold on both sides, and deleting or mapping characters one by one keeps
every match a match, so a record the app accepts is never skipped; anything
the fold over-matches, the app's exact match drops. SearchFold.h drops ASCII
controls other than tab and newline, and decomposes Hangul syllables
arithmetically.

A query character whose case fold is several characters (ß, ﬁ, ŉ) is listed
with the first of them: the app's match compares only that one and lets each
of the rest stand for any one character of the text, so SearchFold.h ends the
query's word after it.

    python3 Tools/AgentHost/generate_search_fold.py
"""
import pathlib
import unicodedata

OUTPUT = pathlib.Path(__file__).resolve().parent / 'src' / 'SearchFoldTable.h'


HANGUL_FILLERS = {0x115F, 0x1160, 0x3164, 0xFFA0}


def ignored(character):
    point = ord(character)
    category = unicodedata.category(character)
    return (category[0] == 'M' or category in ('Cc', 'Cf', 'Cn') or point in HANGUL_FILLERS or
            (point >= 0x80 and category in ('Sk', 'Lm')))


def fold(character):
    def decomposed(text):
        return ''.join(part for part in unicodedata.normalize('NFD', text) if not ignored(part))
    # Every space separator reads as a space, so a query's phrase finds them.
    return ''.join(' ' if unicodedata.category(part)[0] == 'Z' else part
                   for part in decomposed(decomposed(character).casefold()))


def main():
    entries, ignorable, unassigned, expansions = [], [], [], []
    for point in range(0x80, 0x110000):
        if 0xD800 <= point <= 0xDFFF or 0xAC00 <= point <= 0xD7A3:
            continue
        if unicodedata.category(chr(point)) == 'Cn':
            unassigned.append(point)
            continue
        if len(chr(point).casefold()) > 1:
            expansions.append((point, ord(chr(point).casefold()[0])))
        folded = fold(chr(point))
        # A folded Edit preview is folded again when its JSON is decoded.
        assert ''.join(fold(part) for part in folded) == folded, hex(point)
        if not folded:
            ignorable.append(point)
        elif folded != chr(point):
            entries.append((point, folded.encode('utf-8')))
    ranges = []
    for point, kind in sorted([(point, 0) for point in ignorable] + [(point, 1) for point in unassigned]):
        if ranges and ranges[-1][1] == point - 1 and ranges[-1][2] == kind:
            ranges[-1][1] = point
        else:
            ranges.append([point, point, kind])
    # 256-point blocks holding any entry or range; the rest copy as is.
    blocks = bytearray(0x110000 >> 11)
    for point in [point for point, _ in entries] + ignorable + unassigned:
        blocks[point >> 11] |= 1 << ((point >> 8) & 7)
    pool = bytearray()
    rows = []
    for point, encoded in entries:
        assert len(encoded) < 256 and len(pool) < 1 << 32
        rows.append('{0x%04X, %d, %d}' % (point, len(pool), len(encoded)))
        pool += encoded
    lines = [
        '// Generated by Tools/AgentHost/generate_search_fold.py from Unicode %s. Do not edit.'
        % unicodedata.unidata_version,
        '#pragma once',
        '#include <cstdint>',
        '',
        'namespace tessera::search_fold {',
        'struct Entry { uint32_t point, offset; uint8_t length; };',
        'struct Range { uint32_t first, last; bool unassigned; };',
        'struct Expansion { uint32_t point, first; };',
        'inline constexpr unsigned char blocks[] = {',
    ]
    lines += ['    ' + ', '.join(str(byte) for byte in blocks[i:i + 24]) + ',' for i in range(0, len(blocks), 24)]
    lines += ['};', '// Code points the fold drops, and unassigned ones.', 'inline constexpr Range ranges[] = {']
    lines += ['    ' + ', '.join('{0x%04X, 0x%04X, %s}' % (r[0], r[1], 'true' if r[2] else 'false') for r in ranges[i:i + 5]) + ','
              for i in range(0, len(ranges), 5)]
    lines += ['};', 'inline constexpr Entry entries[] = {']
    lines += ['    ' + ', '.join(rows[i:i + 6]) + ',' for i in range(0, len(rows), 6)]
    lines += ['};', 'inline constexpr unsigned char pool[] = {']
    lines += ['    ' + ', '.join(str(byte) for byte in pool[i:i + 24]) + ',' for i in range(0, len(pool), 24)]
    lines += ['};', '// Query characters whose case fold is several, with the first of them.',
              'inline constexpr Expansion expansions[] = {']
    lines += ['    ' + ', '.join('{0x%04X, 0x%04X}' % row for row in expansions[i:i + 8]) + ','
              for i in range(0, len(expansions), 8)]
    lines += ['};', '}', '']
    OUTPUT.write_text('\n'.join(lines))


if __name__ == '__main__':
    main()
